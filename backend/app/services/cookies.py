"""Convert a raw browser `Cookie:` header into a Netscape cookies.txt for yt-dlp.

Instagram/TikTok block anonymous datacenter requests, so yt-dlp needs a logged-in
session. The friendliest input for an analyst is the raw `Cookie:` header copied
from DevTools — but yt-dlp wants a Netscape-format cookie FILE. This converts one
to the other. Pure (string in → string out) so it's unit-tested without network.
"""
from __future__ import annotations

# Far-future expiry (2037) so a copied session cookie isn't treated as expired.
_EXPIRY = "2145916800"


def header_to_netscape(header: str, domain: str) -> str:
    """Build Netscape cookies.txt content from a raw `Cookie:` header.

    `header` is like "sessionid=abc; ds_user_id=123". `domain` is the cookie host,
    e.g. ".instagram.com". Returns the full file text (with the required header line).
    """
    lines = ["# Netscape HTTP Cookie File", "# Generated by AFM for yt-dlp"]
    for pair in header.split(";"):
        pair = pair.strip()
        if not pair or "=" not in pair:
            continue
        name, _, value = pair.partition("=")
        name, value = name.strip(), value.strip()
        if not name:
            continue
        # domain  include_subdomains  path  secure  expiry  name  value
        lines.append("\t".join([domain, "TRUE", "/", "TRUE", _EXPIRY, name, value]))
    return "\n".join(lines) + "\n"
