"""SafeNet KZ signal lexicon — the «признаки» each track looks for.

Every signal is a named, weighted, human-readable indicator with RU + KZ (+ slang /
translit) patterns. Patterns run on the folded text views from `normalize.py`, so
they are written folded: lowercase, ё→е, Kazakh letters as Russian look-alikes
(қ→к, ұ/ү→у, ө→о, ә→а, ғ→г, ң→н, і→и). E.g. «тегін» is matched by «тегин».

Roles:
  core        a signal the track cannot fire without (gate, see scoring.py)
  risk        adds weight
  context     establishes the topic (e.g. «розыгрыш») — small weight
  mitigating  lowers the score (free-contest mechanics, anti-fraud warnings)

`exclude` = regexes tested on a ±40-char window around a hit; a match drops the hit
(«процентная ставка по депозиту» is not a bet; «занос мебели» is not a slot win).

The system never states that a scheme is illegal — a signal is a «признак
возможного нарушения» for a human to verify (SafeNet KZ key principle).
"""
