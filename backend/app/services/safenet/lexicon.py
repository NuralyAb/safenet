# Amount with optional thousands separator / multiplier / currency (folded text).
AMOUNT = r"(?:\d{1,3}(?:[ \u00a0.,]\d{3})+(?:[.,]\d+)?|\d+(?:[.,]\d+)?)"
CURRENCY = r"(?:тг|тенге|тнг|т\b|₸|kzt|руб\w*|₽|\$|usd|долл\w*|usdt|бакс\w*)"
_MONEY = rf"(?:{AMOUNT})\s?(?:к\b|k\b|тыс\w*|мын\w*|млн|миллион\w*)?\s?{CURRENCY}"


@dataclass(frozen=True)
class SignalDef:
    id: str
    track: str
    label: str
    weight: int
    patterns: tuple[str, ...]
    weak: tuple[str, ...] = ()            # matched at half strength
    exclude: tuple[str, ...] = ()
    role: str = "risk"
    description: str = ""
    compiled: tuple = field(default=(), compare=False, repr=False)
    compiled_weak: tuple = field(default=(), compare=False, repr=False)
    compiled_exclude: tuple = field(default=(), compare=False, repr=False)


def _sig(id: str, track: str, label: str, weight: int, patterns, *, weak=(), exclude=(),
         role: str = "risk", description: str = "") -> SignalDef:
    flags = re.IGNORECASE | re.UNICODE
    return SignalDef(
        id=id, track=track, label=label, weight=weight, patterns=tuple(patterns),
        weak=tuple(weak), exclude=tuple(exclude), role=role, description=description,
        compiled=tuple(re.compile(p, flags) for p in patterns),
        compiled_weak=tuple(re.compile(p, flags) for p in weak),
        compiled_exclude=tuple(re.compile(p, flags) for p in exclude),
    )


